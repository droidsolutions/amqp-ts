import assert from "node:assert/strict";
import { test } from "node:test";
import { analyzeCommits } from "@semantic-release/commit-analyzer";
import { generateNotes } from "@semantic-release/release-notes-generator";
import config, { stripTrailers } from "../release.config.mjs";

const noop = () => {};
const logger = { log: noop, warn: noop, error: noop, success: noop };

/** The options the release config passes to the given plugin. */
function pluginOptions(name) {
  const entry = config.plugins.find((plugin) => Array.isArray(plugin) && plugin[0] === name);
  assert.ok(entry, `${name} must be configured with options`);
  return entry[1];
}

/** Release notes generated by the configured release-notes-generator for the given commit messages. */
function notesFor(...messages) {
  return generateNotes(pluginOptions("@semantic-release/release-notes-generator"), {
    commits: messages.map((message, i) => ({ hash: String(i).repeat(40), message })),
    lastRelease: { gitTag: "v3.0.4" },
    nextRelease: { gitTag: "v4.0.0", version: "4.0.0" },
    options: { repositoryUrl: "https://github.com/droidsolutions/amqp-ts.git" },
    cwd: process.cwd(),
    logger,
  });
}

test("stripTrailers removes trailer lines and trailing blank lines", () => {
  const text =
    "allowed engines constrained\nto align with X\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nClaude-Session: https://example.invalid/s\nSigned-off-by: A B <a@b.c>";
  assert.equal(stripTrailers(text), "allowed engines constrained\nto align with X");
});

test("stripTrailers keeps ordinary lines containing a colon", () => {
  assert.equal(stripTrailers("Note: heartbeat 0 now disables"), "Note: heartbeat 0 now disables");
});

test("generated notes contain the breaking change but no trailers", async () => {
  const notes = await notesFor(
    "feat!: drop x\n\nBREAKING CHANGE: x is gone\n\nCo-authored-by: C <c@d.e>\nSigned-off-by: A <a@b.c>",
  );
  assert.match(notes, /x is gone/);
  assert.doesNotMatch(notes, /Co-authored-by|Signed-off-by/i);
});

test("commits marked breaking with ! are listed under their type", async () => {
  const notes = await notesFor(
    "feat!: drop x\n\nBREAKING CHANGE: x is gone",
    "fix(deps)!: update y to 2.x\n\nBREAKING CHANGE: y changed",
  );
  assert.match(notes, /### Features\n\n\* drop x/);
  assert.match(notes, /### Bug Fixes\n\n\* \*\*deps:\*\* update y to 2\.x/);
  assert.doesNotMatch(notes, /feat!|fix\(deps\)!/);
});

test("a ! without a BREAKING CHANGE footer still is a breaking change", async () => {
  const commits = [{ hash: "a".repeat(40), message: "feat!: drop x" }];
  const releaseType = await analyzeCommits(pluginOptions("@semantic-release/commit-analyzer"), {
    commits,
    logger,
    cwd: process.cwd(),
  });
  assert.equal(releaseType, "major");
  assert.match(await notesFor("feat!: drop x"), /### BREAKING CHANGES\n\n\* drop x/);
});
